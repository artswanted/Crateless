        public static string T(string en, string? ru = null)
        {
            var two = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            if (Extra.TryGetValue(two, out var map) && map.TryGetValue(en, out var hit) && hit.Length > 0)
                return hit;
            if (string.Equals(two, "en", StringComparison.OrdinalIgnoreCase))
                return en;

            return Nebula.NebulaText.T(en, ru ?? en);
        }

        public static string Tf(string en, string? ru, params object[] args)
        {
            string fmt = T(en, ru);
            try { return string.Format(CultureInfo.CurrentUICulture, fmt, args); }
            catch { return string.Format(CultureInfo.InvariantCulture, en, args); }
        }

        public static string FormatNumber(double value, string format = "0.#") =>
            value.ToString(format, CultureInfo.CurrentUICulture);

        public static string FormatTime(DateTimeOffset dt) =>
            dt.ToLocalTime().ToString("T", CultureInfo.CurrentUICulture);

        public static string FormatShortTime(DateTime dt) =>
            dt.ToString("HH:mm:ss", CultureInfo.CurrentUICulture);
    }
